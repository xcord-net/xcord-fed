namespace Xcord.Entities;

/// <summary>
/// Default sort order for forum channel posts.
/// </summary>
public enum ForumSort
{
    /// <summary>
    /// Sort by latest activity (most recent reply).
    /// </summary>
    LatestActivity = 0,

    /// <summary>
    /// Sort by creation date (newest posts first).
    /// </summary>
    CreationDate = 1
}
